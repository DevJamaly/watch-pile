export interface OmdbSearchResponse {
  Search?: MovieData[]; // "?" = might be missing
  Response: 'True' | 'False';
  Error?: string;
}

export interface OmdbApiMovie {
  Response: 'True';
  Title: string;
  Year: string;
  Poster: string;
  Runtime: string;
  imdbRating: string;
  Plot: string;
  Released: string;
  Actors: string;
  Director: string;
  Genre: string;
}

interface OmdbApiFailure {
  Response: 'False';
  Error: string;
}

export type OmdbResponse = OmdbApiMovie | OmdbApiFailure;

